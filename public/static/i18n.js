let CURRENT_LANGUAGE = "en";

function setLanguage(lang) {
    if (!I18N_DATA[lang]) {
        console.warn(`Language ${lang} not found, defaulting to en`);
        lang = "en";
    }
    CURRENT_LANGUAGE = lang;
    localStorage.setItem("qcredit_portal_lang", lang);
    document.documentElement.lang = lang;

    const dict = I18N_DATA[lang];

    // 1. Text elements with data-i18n
    document.querySelectorAll("[data-i18n]").forEach((el) => {
        const key = el.getAttribute("data-i18n");
        if (dict[key]) {
            el.textContent = dict[key];
        }
    });

    // 2. Placeholder attributes with data-i18n-ph
    document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
        const key = el.getAttribute("data-i18n-ph");
        if (dict[key]) {
            el.placeholder = dict[key];
        }
    });

    // 3. Dropdowns and sector options
    const sectorSelect = document.getElementById("app-sector");
    if (sectorSelect) {
        const sectorKeys = {
            PRIVATE_CORPORATE: "sector_corp",
            CENTRAL_GOVT: "sector_cg",
            STATE_GOVT: "sector_sg",
            PSU_BANKING: "sector_psu",
            DEFENSE_ARMED: "sector_def",
            HEALTHCARE_DOCTOR: "sector_med",
            ACADEMIC_EDUCATION: "sector_edu",
            LEGAL_JUDICIARY: "sector_leg",
            BUSINESS_ENTERPRISE: "sector_biz"
        };
        Array.from(sectorSelect.options).forEach((opt) => {
            const trKey = sectorKeys[opt.value];
            if (trKey && dict[trKey]) {
                opt.textContent = dict[trKey];
            }
        });
    }

    // 4. Update Language select dropdown UI if present
    const langSelect = document.getElementById("app-language-select");
    if (langSelect && langSelect.value !== lang) {
        langSelect.value = lang;
    }

    // 5. Notify app.js of language update for dynamic workings & memos
    window.dispatchEvent(new CustomEvent("appLanguageChanged", { detail: { lang, dict } }));
}

function getTranslation(key, fallback = "") {
    const dict = I18N_DATA[CURRENT_LANGUAGE] || I18N_DATA.en;
    return dict[key] || fallback;
}

window.setLanguage = setLanguage;
window.getTranslation = getTranslation;
window.getCurrentLanguage = () => CURRENT_LANGUAGE;

// Auto-initialize on DOM ready
document.addEventListener("DOMContentLoaded", () => {
    const saved = localStorage.getItem("qcredit_portal_lang") || "en";
    setLanguage(saved);
});

